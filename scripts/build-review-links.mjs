#!/usr/bin/env node
/**
 * build-review-links.mjs — two chifbay.com links that go straight to a review form.
 *
 * WHY
 *
 * review.html asks for a star rating first and only then shows Google and
 * Tripadvisor. That is the right page for a guest who lands on the site, and
 * the wrong thing to send by WhatsApp after a trip: the skipper wants to paste
 * two links and have the guest post on BOTH. Sending them back to a page where
 * they pick one means most pick one.
 *
 *   https://chifbay.com/r/google
 *   https://chifbay.com/r/tripadvisor
 *
 * WHY THIS IS NOT A ONE-LINE META REFRESH
 *
 * These links get sent in WhatsApp, so most taps arrive inside an in-app
 * browser, where the guest is NOT signed in to Google — a plain redirect drops
 * them on a sign-in wall and the review never happens. review.html already
 * solves that and this reuses the same escape: Android hands off to the default
 * browser with intent://, iOS tries x-safari- and falls back. Both need a real
 * tap, so in an in-app browser the page shows one button instead of
 * redirecting. Everywhere else it redirects immediately and is never seen.
 *
 * SINGLE SOURCE OF TRUTH
 *
 * The two URLs are read out of review.html rather than written here. They are
 * long, they contain ids that change when a listing is renamed, and three
 * copies would drift — Tripadvisor's already had, see the note below.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const page = readFileSync(join(ROOT, "review.html"), "utf8");
const pick = (name) => {
  const m = page.match(new RegExp(`var\\s+${name}\\s*=\\s*'([^']+)'`));
  if (!m) {
    console.error(`could not find ${name} in review.html — the review page changed shape.`);
    console.error("Refusing to write a redirect to a URL I had to guess.");
    process.exit(1);
  }
  return m[1];
};

const TARGETS = {
  google: {
    url: pick("GURL"),
    expect: /^https:\/\/search\.google\.com\/local\/writereview\?placeid=/,
    brand: "Google",
  },
  tripadvisor: {
    url: pick("TURL"),
    // Tripadvisor blocks curl and automated browsers alike (DataDome), so this
    // was confirmed the only way it can be: by opening chifbay.com/r/tripadvisor
    // in the real browser on 2026-08-30 and landing on "Write a review".
    // The listing was renamed (was g189167 ChifBay_Luxury_Yacht_Experiences);
    // the old URL still 301s here and the d34387047 id never changed.
    expect: /^https:\/\/www\.tripadvisor\.com\/UserReviewEdit-g\d+-d\d+-/,
    brand: "Tripadvisor",
  },
};

// Three strings per language. The card is only ever seen inside an in-app
// browser, which is most of them, because these links arrive by WhatsApp.
const T = {
  en: { lead: "Thanks for sailing with us.", cta: (b) => `Open ${b} →`, hint: "You're in an in-app browser. If it asks you to sign in, open this link in your normal browser." },
  fr: { lead: "Merci d'avoir navigué avec nous.", cta: (b) => `Ouvrir ${b} →`, hint: "Vous êtes dans un navigateur intégré. S'il demande de vous connecter, ouvrez ce lien dans votre navigateur habituel." },
  de: { lead: "Danke, dass Sie mit uns gesegelt sind.", cta: (b) => `${b} öffnen →`, hint: "Sie sind in einem In-App-Browser. Wenn eine Anmeldung verlangt wird, öffnen Sie den Link im normalen Browser." },
  pt: { lead: "Obrigado por navegar connosco.", cta: (b) => `Abrir ${b} →`, hint: "Está num navegador dentro da app. Se pedir para iniciar sessão, abra este link no seu navegador normal." },
  es: { lead: "Gracias por navegar con nosotros.", cta: (b) => `Abrir ${b} →`, hint: "Estás en un navegador dentro de la app. Si te pide iniciar sesión, abre este enlace en tu navegador normal." },
  it: { lead: "Grazie per aver navigato con noi.", cta: (b) => `Apri ${b} →`, hint: "Sei in un browser interno all'app. Se chiede di accedere, apri questo link nel browser normale." },
};

function html(brand, url) {
  const strings = Object.fromEntries(
    Object.entries(T).map(([k, v]) => [k, { lead: v.lead, cta: v.cta(brand), hint: v.hint }]),
  );
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width,initial-scale=1"/>
<!-- Generated by scripts/build-review-links.mjs — edit the URL in review.html, not here. -->
<title>Review Chifbay on ${brand}</title>
<meta name="robots" content="noindex,nofollow"/>
<noscript><meta http-equiv="refresh" content="0;url=${url}"/></noscript>
<style>
  :root{color-scheme:dark}
  html,body{margin:0;height:100%}
  body{background:#1a2634;color:#f2ede2;
    font:400 16px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Helvetica,Arial,sans-serif;
    display:grid;place-items:center;padding:24px;text-align:center}
  .card{max-width:22rem}
  .mark{font:500 13px/1 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif;
    letter-spacing:.28em;text-transform:uppercase;color:#c9a45c;margin:0 0 1.6rem}
  p{margin:0 0 1.6rem;color:rgba(242,237,226,.82)}
  a.go{display:block;padding:1rem 1.4rem;border-radius:2px;background:#c9a45c;color:#1a2634;
    font-weight:600;text-decoration:none}
  a.go:active{opacity:.85}
  .hint{margin:1.4rem 0 0;font-size:13px;color:rgba(242,237,226,.55);display:none}
  .hint.show{display:block}
</style>
</head>
<body>
<div class="card">
  <p class="mark">Chifbay</p>
  <p id="lead">Thanks for sailing with us.</p>
  <a class="go" id="go" href="${url}" rel="noopener">Open ${brand} →</a>
  <p class="hint" id="hint"></p>
</div>
<script>
(function(){
  var URL_ = ${JSON.stringify(url)};
  var S = ${JSON.stringify(strings)};

  var ua = navigator.userAgent || '';
  var inApp = /(Instagram|FBAN|FBAV|FB_IAB|WhatsApp|Messenger|TikTok|Snapchat|musical_ly|Line\\/)/i.test(ua);
  var iOS = /iPhone|iPad|iPod/i.test(ua);
  var android = /Android/i.test(ua);

  // Not in an in-app browser: this page has no reason to be looked at.
  if (!inApp) { location.replace(URL_); return; }

  var lang = (navigator.language || 'en').slice(0,2).toLowerCase();
  var s = S[lang] || S.en;
  document.documentElement.lang = S[lang] ? lang : 'en';
  document.getElementById('lead').textContent = s.lead;

  var go = document.getElementById('go');
  go.textContent = s.cta;

  var hint = document.getElementById('hint');
  hint.textContent = s.hint;
  hint.className = 'hint show';

  // Android in-app browsers honour intent:// and hand the tap to the DEFAULT
  // browser, where the guest is already signed in. Same trick as review.html.
  if (android) {
    go.href = 'intent://' + URL_.replace(/^https?:\\/\\//,'') + '#Intent;scheme=https;end';
  }

  // iOS has no reliable programmatic escape. Try the Safari scheme on the tap
  // and fall back to the plain link if it is ignored.
  if (iOS) {
    go.addEventListener('click', function(ev){
      ev.preventDefault();
      var t = Date.now();
      location.href = 'x-safari-' + URL_;
      setTimeout(function(){
        if (!document.hidden && Date.now() - t < 2400) location.href = URL_;
      }, 1500);
    });
  }
})();
</script>
</body>
</html>
`;
}

let wrote = 0;
for (const [slug, t] of Object.entries(TARGETS)) {
  if (!t.expect.test(t.url)) {
    console.error(`${slug}: the URL in review.html does not look like a ${t.brand} review link:`);
    console.error(`  ${t.url}`);
    process.exit(1);
  }
  const dir = join(ROOT, "r", slug);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "index.html"), html(t.brand, t.url));
  console.log(`r/${slug}/  ->  ${t.url}`);
  wrote++;
}
console.log(`\n${wrote} link(s) written. Send these:`);
for (const slug of Object.keys(TARGETS)) console.log(`  https://chifbay.com/r/${slug}`);
